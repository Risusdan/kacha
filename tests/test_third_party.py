def meta(expression=None, licence=None, classifiers=(), version="1.0"):
    """The metadata of a package, as importlib.metadata gives it (an email message)."""
    message = Message()
    message["Name"] = "pkg"
    message["Version"] = version
    if expression is not None:
        message["License-Expression"] = expression
    if licence is not None:
        message["License"] = licence
    for classifier in classifiers:
        message["Classifier"] = classifier
    return message


