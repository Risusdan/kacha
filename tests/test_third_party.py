REGISTER = """\
# Register

## 直接相依

| 名稱 | 版本或來源 | 授權 | 能否商業使用 | 用途 | 查核日期 |
|---|---|---|---|---|---|
| numpy | 2.5 | BSD-3-Clause | 可 | x | 2026-11-11 |

## 間接相依

| 名稱 | 版本或來源 | 授權 | 能否商業使用 | 用途 | 查核日期 |
|---|---|---|---|---|---|
| `Regex` | 2026 | Apache-2.0 AND CNRI-Python | 可 | x | 2026-11-11 |
| typing_extensions | 4 | PSF-2.0 | 可（條件） | x | 2026-11-11 |
| cffi | 2 | MIT-0 | 待查 | x | 2026-11-11 |
| libsndfile（soundfile 隨附） | 1 | LGPL-2.1 | 可 | x | 2026-11-11 |

```text
| shown | in | code | 可 | x | y |
```

### 備註

| 名稱 | 說明 | 授權 | 能否商業使用 |
|---|---|---|---|
| tqdm | a table of the subsection | MPL-2.0 | 可 |

## 其他

| 名稱 | 版本或來源 | 授權 | 能否商業使用 | 用途 | 查核日期 |
|---|---|---|---|---|---|
| after | 1 | MIT | 可 | x | 2026-11-11 |
"""


def test_register_rows_are_the_rows_of_the_indirect_section(tp):
    rows = tp.register_rows(REGISTER)
    assert rows == {
        "regex": [("2026", "可")],
        "typing-extensions": [("4", "可（條件）")],
        "cffi": [("2", "待查")],
        "libsndfile": [("1", "可")],
        "tqdm": [("a", "可")],
    }


def register_with(tp, *rows):
    """The rows (name, version cell, 能否商業使用 cell) as the indirect section of a register, read by register_rows."""
    lines = ["## 間接相依", "", "| 名稱 | 版本或來源 | 授權 | 能否商業使用 |", "|---|---|---|---|"]
    lines += [f"| {name} | {version} | CC0-1.0 | {usable} |" for name, version, usable in rows]
    return tp.register_rows("\n".join(lines) + "\n")


@pytest.mark.parametrize(
    ("cell", "version"),
    [
        ("0.4.4（pyproject 固定）", "0.4.4"),
        ("0.4.4 (pinned)", "0.4.4"),
        ("0.55.0 pinned", "0.55.0"),
        ("2.5.4", "2.5.4"),
        ("soundfile 0.14.0", "soundfile"),
    ],
)
def test_version_cell_with_a_note(tp, cell, version):
    assert register_with(tp, ("a", cell, "可")) == {"a": [(version, "可")]}


def test_a_name_with_several_rows_keeps_each_of_them_in_order(tp):
    rows = register_with(tp, ("A_b", "2.5.3", "可"), ("a-b", "2.5.4", "待查"))
    assert rows == {"a-b": [("2.5.3", "可"), ("2.5.4", "待查")]}


def test_register_without_the_indirect_section_has_no_rows(tp):
    assert tp.register_rows("# x\n\n## 直接相依\n\n| numpy | 1 | MIT | 可 | x | y |\n") == {}


